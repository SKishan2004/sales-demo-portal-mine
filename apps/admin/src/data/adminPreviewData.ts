export function derivePreviewDashboard(): DashboardSummaryDTO {
  const published = PREVIEW_PRODUCTS.filter((p) => p.publicationStatus === 'published').length;
  const totalScreenshots = PREVIEW_PRODUCTS.reduce((acc, p) => acc + p.images.length, 0);
  const totalVideos = PREVIEW_PRODUCTS.reduce((acc, p) => acc + p.videos.length, 0);

  return {
    metrics: {
      totalProducts: PREVIEW_PRODUCTS.length,
      publishedProducts: published,
      draftProducts: PREVIEW_PRODUCTS.length - published,
      totalCategories: PREVIEW_CATEGORIES.length,
      totalProductTypes: PREVIEW_PRODUCT_TYPES.length,
      totalVideos,
      totalScreenshots,
      totalAdministrators: PREVIEW_USERS.length,
      activeAdministrators: PREVIEW_USERS.filter((u) => u.status === 'active').length,
    },
    categoryBreakdown: PREVIEW_CATEGORIES.map((cat) => ({
      categoryId: cat.id,
      categoryName: cat.name,
      productCount: PREVIEW_PRODUCTS.filter((p) => p.categoryId === cat.id).length,
    })),
    recentlyUpdatedProducts: [...PREVIEW_PRODUCTS]
      .sort((a, b) => b.updatedAt.localeCompare(a.updatedAt))
      .slice(0, 4),
    recentlyAddedProducts: [...PREVIEW_PRODUCTS].slice(-4).reverse(),
    recentActivity: PREVIEW_ACTIVITY_LOGS,
  };
}

