export function buildPreviewActor(
  roleSlug: RoleSlug,
  editorCanPublish = false,
): AdminUserDTO {
  const role = PREVIEW_ROLES.find((r) => r.slug === roleSlug) ?? PREVIEW_ROLES[0]!;
  const permissions = [...role.permissions];
  if (roleSlug === 'content_manager' && editorCanPublish && !permissions.includes('products:publish')) {
    permissions.push('products:publish');
  }
  return {
    id: `preview-${roleSlug}`,
    name: `UI Preview (${role.name})`,
    email: `${roleSlug}@preview.local`,
    username: `preview_${roleSlug}`,
    roleSlug,
    roleName: role.name,
    status: 'active',
    canPublishOverride: roleSlug === 'content_manager' ? editorCanPublish : null,
    permissions,
    lastLoginAt: new Date().toISOString(),
    createdAt: '2026-11-20T09:00:00.000Z',
  };
}

